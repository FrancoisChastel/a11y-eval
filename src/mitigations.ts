import type { Finding, ManualReviewItem, RemediationGroup, Report } from './types.ts'

const groupKey = (g: Pick<RemediationGroup, 'engine' | 'ruleId'>): string => `${g.engine}::${g.ruleId}`

const codeBlock = (lang: string, content: string): string => `\`\`\`${lang}\n${content}\n\`\`\``

const instanceRow = (f: Finding, index: number): string[] => {
  const location = f.engine === 'static' ? `source \`${f.targets[0] ?? f.page}\`` : `\`${f.targets[0] ?? '?'}\` on ${f.page}`
  const lines = [`${index + 1}. ${location}${f.baselineStatus ? ` _(${f.baselineStatus})_` : ''}`]
  if (f.html) lines.push(`   ${codeBlock('html', f.html.trim()).replaceAll('\n', '\n   ')}`)
  return lines
}

const renderGroup = (group: RemediationGroup, instances: Finding[], index: number, total: number): string[] => {
  const r = group.recommendation
  const docsUrl = instances.find((f) => f.helpUrl)?.helpUrl
  const lines = [
    `## Group ${index + 1} of ${total} — [${group.impact}] \`${group.ruleId}\``,
    '',
    `WCAG ${group.wcag.join(', ') || 'best practice'} · engine: ${group.engine} · ${group.findingCount} instance(s) on ${group.pages.length} page(s) · estimated effort: ${r.effort}`,
    '',
    `**Fix:** ${r.summary}`,
    '',
    `**Steps:**`,
    ...r.steps.map((s, i) => `${i + 1}. ${s}`),
    '',
  ]
  if (r.example) {
    lines.push(`**Before / after:**`, '', codeBlock('html', `<!-- WRONG -->\n${r.example.bad}\n\n<!-- RIGHT -->\n${r.example.good}`), '')
  }
  lines.push(`**Do NOT:**`, ...r.pitfalls.map((p) => `- ${p}`), '')
  if (docsUrl) lines.push(`**Rule docs:** ${docsUrl}`, '')
  lines.push(`**Instances to fix (all of them):**`, '', ...instances.flatMap(instanceRow), '')
  if (group.engine !== 'static') {
    lines.push(`_Locate in source: grep the codebase for the snippet, its class names, or nearby text._`, '')
  }
  return lines
}

const renderManualFailure = (item: ManualReviewItem, how: string | undefined): string[] => {
  const lines = [
    `### WCAG ${item.sc} — manual review failure [${item.severity ?? 'serious'}]`,
    '',
    `**Evidence from the reviewer:** ${item.evidence?.trim() || '(none recorded — ask the reviewer or reproduce before fixing)'}`,
  ]
  if (item.pages && item.pages.length > 0) lines.push('', `**Affected pages:** ${item.pages.join(', ')}`)
  if (item.screenshots && item.screenshots.length > 0) lines.push('', `**Evidence screenshots:** ${item.screenshots.join(', ')}`)
  if (how) lines.push('', `**How this criterion is judged:** ${how}`)
  lines.push(
    '',
    `**Mitigation:** no deterministic catalog entry exists for manual criteria — derive the change from the evidence above, apply it, then re-review this criterion by hand or agent (automation cannot verify it).`,
    '',
  )
  return lines
}

/**
 * Renders the agent-facing mitigation work order: an executable markdown document
 * with every instance to fix, the catalog guidance including anti-fixes, manual
 * review failures with their evidence, and the verification loop. Written
 * automatically after evaluation and merge; regenerable with the `mitigate`
 * subcommand.
 */
export const renderMitigations = (report: Report): string => {
  const plan = (report.remediationPlan ?? []).filter((g) => g.engine !== 'human' && g.engine !== 'agent')
  const findingsByGroup = new Map<string, Finding[]>()
  for (const f of report.findings) {
    if (f.engine === 'human' || f.engine === 'agent') continue
    const key = groupKey(f)
    findingsByGroup.set(key, [...(findingsByGroup.get(key) ?? []), f])
  }

  const manualFails = report.manualReview?.items.filter((i) => i.status === 'fail') ?? []
  const needsExpert = report.manualReview?.items.filter((i) => i.status === 'needs-expert') ?? []
  const howBySc = new Map(report.manualChecklist.map((c) => [c.sc, c.how]))

  const target = report.meta?.repo ?? (report.meta?.seeds ?? []).join(', ')
  const headline = report.overall ?? report.verdict

  const lines: string[] = [
    `# Mitigation Work Order — WCAG 2.2 AA`,
    '',
    `Audience: a coding agent or developer executing accessibility fixes. Generated by a11y-eval ${report.version} on ${report.finishedAt}.`,
    '',
    `Target: ${target} · current result: **${headline}** · ${plan.length} fix group(s)` +
      (manualFails.length > 0 ? ` + ${manualFails.length} manual failure(s)` : ''),
    '',
    `## Rules of engagement`,
    '',
    `1. Work groups top to bottom — they are ordered by impact, then reach.`,
    `2. Fix one group per change-set, then run the verification step. Do not batch unrelated groups.`,
    `3. Every **Do NOT** is binding. Suppressing a rule, hiding an element from assistive technology, or hard-coding around the scanner is a failed fix.`,
    `4. Fix every listed instance of a group — a group is cleared only when its rule no longer appears in a re-run.`,
    `5. Do not delete features to pass: the fix must keep the user-facing capability working for everyone.`,
    '',
  ]

  if (plan.length === 0 && manualFails.length === 0) {
    lines.push(`Nothing to fix: no automated findings${report.manualReview ? ' and no manual failures' : ''}. If the manual review is incomplete, complete it before concluding.`, '')
  }

  for (const [index, group] of plan.entries()) {
    lines.push(...renderGroup(group, findingsByGroup.get(groupKey(group)) ?? [], index, plan.length))
  }

  if (manualFails.length > 0) {
    lines.push(`## Manual review failures`, '', `These came from a human or agent review, not a scanner — the evidence below is the specification.`, '')
    for (const item of manualFails) lines.push(...renderManualFailure(item, howBySc.get(item.sc)))
  }

  if (needsExpert.length > 0) {
    lines.push(
      `## Requires a human specialist (do not attempt automated fixes)`,
      '',
      ...needsExpert.map((i) => `- WCAG ${i.sc}: ${i.evidence?.trim() || 'flagged needs-expert without notes'}`),
      '',
    )
  }

  lines.push(`## Verification`, '')
  if (report.meta?.command) {
    lines.push(
      `1. Re-run the evaluation with this report as baseline:`,
      '',
      codeBlock('bash', `${report.meta.command} --baseline <path-to-this-run>/report.json`),
      '',
      `2. Success = every group's rule gone (they appear under "fixed"), \`new\` count stays 0, verdict is no longer fail.`,
    )
  } else {
    lines.push(`1. Re-run the same a11y-eval invocation with \`--baseline\` pointing at this run's report.json; every group's rule must appear as fixed with no new findings.`)
  }
  if (manualFails.length > 0) {
    lines.push(`3. Re-review the failed manual criteria (review UI or agent pass) and re-merge: automation cannot confirm those fixes.`)
  }
  lines.push('', `> Reminder: a clean re-run is "no known violations", never "WCAG compliant".`, '')

  return lines.join('\n')
}
